BEGIN;
SET LOCAL standard_conforming_strings = on;
DO $$
DECLARE
    schema_name TEXT;
BEGIN
    IF current_database() <> 'food_to_eat' THEN
        RAISE EXCEPTION 'Refusing reset: expected food_to_eat, connected to %', current_database();
    END IF;
    FOR schema_name IN
        SELECT nspname FROM pg_namespace
        WHERE nspname <> 'information_schema'
          AND left(nspname, 3) <> 'pg_'
        ORDER BY nspname
    LOOP
        EXECUTE format('DROP SCHEMA IF EXISTS %I CASCADE', schema_name);
    END LOOP;
END;
$$;
CREATE SCHEMA public AUTHORIZATION CURRENT_USER;
SET LOCAL search_path = public;

CREATE TABLE cuisines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

CREATE TABLE types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

CREATE TABLE ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

CREATE TABLE flavors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

CREATE TABLE foods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    description TEXT NOT NULL,
    cuisine_id BIGINT NOT NULL REFERENCES cuisines(id),
    image_url TEXT
);

CREATE TABLE food_types (
    food_id BIGINT NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    type_id BIGINT NOT NULL REFERENCES types(id),
    PRIMARY KEY (food_id, type_id)
);
CREATE INDEX food_types_type_id_idx ON food_types (type_id, food_id);

CREATE TABLE food_ingredients (
    food_id BIGINT NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredients(id),
    PRIMARY KEY (food_id, ingredient_id)
);
CREATE INDEX food_ingredients_ingredient_id_idx ON food_ingredients (ingredient_id, food_id);

CREATE TABLE food_flavors (
    food_id BIGINT NOT NULL REFERENCES foods(id) ON DELETE CASCADE,
    flavor_id BIGINT NOT NULL REFERENCES flavors(id),
    PRIMARY KEY (food_id, flavor_id)
);
CREATE INDEX food_flavors_flavor_id_idx ON food_flavors (flavor_id, food_id);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    cuisine_id BIGINT UNIQUE REFERENCES cuisines(id),
    type_id BIGINT UNIQUE REFERENCES types(id),
    ingredient_id BIGINT UNIQUE REFERENCES ingredients(id),
    flavor_id BIGINT UNIQUE REFERENCES flavors(id),
    CONSTRAINT categories_one_target CHECK (
        num_nonnulls(cuisine_id, type_id, ingredient_id, flavor_id) = 1
    )
);
CREATE TABLE questions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    question TEXT NOT NULL CHECK (btrim(question) <> '')
);
CREATE INDEX questions_category_idx ON questions(category_id);
CREATE TABLE recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    question_id INTEGER REFERENCES questions(id),
    food_id BIGINT NOT NULL REFERENCES foods(id),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX recommendations_food_idx ON recommendations(food_id);
CREATE INDEX recommendations_question_idx ON recommendations(question_id);
CREATE INDEX foods_cuisine_idx ON foods(cuisine_id);

CREATE VIEW food_category_membership AS
    SELECT f.id AS food_id, c.id AS category_id
    FROM foods f JOIN categories c ON c.cuisine_id = f.cuisine_id
    UNION
    SELECT ft.food_id, c.id FROM food_types ft
    JOIN categories c ON c.type_id = ft.type_id
    UNION
    SELECT fi.food_id, c.id FROM food_ingredients fi
    JOIN categories c ON c.ingredient_id = fi.ingredient_id
    UNION
    SELECT ff.food_id, c.id FROM food_flavors ff
    JOIN categories c ON c.flavor_id = ff.flavor_id;

